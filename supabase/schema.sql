-- Resell Radar scan-history table
-- Run this in Supabase SQL Editor once. Keep the service-role key server-side only.
create table if not exists public.scan_history (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  keyword text not null,
  marketplace text not null,
  total_results integer not null default 0,
  results jsonb not null default '[]'::jsonb
);

create index if not exists scan_history_created_at_idx on public.scan_history (created_at desc);
create index if not exists scan_history_keyword_idx on public.scan_history (keyword);

alter table public.scan_history enable row level security;
-- No anon/authenticated policies are created. Access is intended through the Netlify
-- function using the server-only SUPABASE_SERVICE_ROLE_KEY.
